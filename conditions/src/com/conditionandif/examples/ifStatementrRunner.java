package com.conditionandif.examples;

public class ifStatementrRunner {

	public static void main(String[] args) {

		int i = 5;
		if (i == 10) {
			System.out.println("i = 10");
		} else if (i < 9) {
			System.out.println("i != 10");
		} else {
			System.out.println("i = 10 and i != 10");
		}
	}
}
